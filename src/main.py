def load_latest_bundle(symbol: str) -> dict | None:
    """Load the most recent scraped JSON for a given symbol."""
    symbol = symbol.upper()
    files = sorted(BUNDLES_DIR.glob(f"{symbol}_*.json"), reverse=True)
    if not files:
        return None
    with open(files[0], encoding="utf-8") as f:
        return json.load(f)


