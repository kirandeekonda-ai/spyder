"""
main.py - Hybrid Stock Analyst CLI Orchestrator
================================================
PURPOSE:
  The single entry point for the entire system.
  Coordinates: Scraping -> Rule Evaluation -> Notion Sync -> Report

HOW MODEL SWITCHING WORKS:
  Phase 1 (Data)        : Runs locally via Python (scraper + rule engine)
  Phase 2 (Math/Calc)  : Antigravity (Gemini Pro) — deep reading, pattern recognition
  Phase 3 (Synthesis)  : Antigravity summarizes and gives final verdict with reasoning

USAGE:
  python src/main.py analyze HDFCBANK
  python src/main.py analyze HDFCBANK --portfolio 1500000
  python src/main.py analyze HDFCBANK --login          (force re-login to Tijori)
  python src/main.py watchlist                          (show all watchlisted stocks)
  python src/main.py ledger                             (show portfolio)
  python src/main.py add-position HDFCBANK 1800 10     (add to ledger: symbol price qty)
  python src/main.py demo HDFCBANK                     (demo with mock data, no browser)
"""

